export function evaluateBoard(chess: Chess): number {
  if (chess.isCheckmate()) {
    return chess.turn() === 'w' ? -20000 : 20000;
  }
  if (chess.isDraw()) {
    return 0;
  }

  let score = 0;
  const board = chess.board();

  for (let r = 0; r < 8; r++) {
    for (let c = 0; c < 8; c++) {
      const piece = board[r][c];
      if (!piece) continue;

      const val = PIECE_VALS[piece.type] || 0;
      const pstVal = PST[piece.type] ? (piece.color === 'w' ? PST[piece.type][r][c] : PST[piece.type][7 - r][c]) : 0;
      const total = val + pstVal;

      if (piece.color === 'w') {
        score += total;
      } else {
        score -= total;
      }
    }
  }

  return score;
}

export interface BestMoveResult {
  move: Move | null;
  score: number;
}

export function findBestMove(chess: Chess, depth: number = 3): BestMoveResult {
  const isMaximizing = chess.turn() === 'w';
  const moves = chess.moves({ verbose: true });
  if (moves.length === 0) {
    return { move: null, score: evaluateBoard(chess) };
  }

  // Shuffle moves slightly for human-like variety in equal positions
  moves.sort(() => Math.random() - 0.5);

  let bestMove: Move | null = null;
  let bestScore = isMaximizing ? -Infinity : Infinity;

  for (const move of moves) {
    chess.move(move);
    const score = minimax(chess, depth - 1, -Infinity, Infinity, !isMaximizing);
    chess.undo();

    if (isMaximizing) {
      if (score > bestScore) {
        bestScore = score;
        bestMove = move;
      }
    } else {
      if (score < bestScore) {
        bestScore = score;
        bestMove = move;
      }
    }
  }

  return { move: bestMove, score: bestScore };
}

function minimax(chess: Chess, depth: number, alpha: number, beta: number, isMaximizing: boolean): number {
  if (depth === 0 || chess.isGameOver()) {
    return evaluateBoard(chess);
  }

  const moves = chess.moves({ verbose: true });
  if (isMaximizing) {
    let maxEval = -Infinity;
    for (const move of moves) {
      chess.move(move);
      const evalScore = minimax(chess, depth - 1, alpha, beta, false);
      chess.undo();
      maxEval = Math.max(maxEval, evalScore);
      alpha = Math.max(alpha, evalScore);
      if (beta <= alpha) break;
    }
    return maxEval;
  } else {
    let minEval = Infinity;
    for (const move of moves) {
      chess.move(move);
      const evalScore = minimax(chess, depth - 1, alpha, beta, true);
      chess.undo();
      minEval = Math.min(minEval, evalScore);
      beta = Math.min(beta, evalScore);
      if (beta <= alpha) break;
    }
    return minEval;
  }
}

export function computeCapturedPieces(chess: Chess): {
  whiteCaptured: PieceSymbol[]; // Black pieces captured by White
  blackCaptured: PieceSymbol[]; // White pieces captured by Black
  whiteAdvantage: number;
} {
  const initialCounts: Record<Color, Record<PieceSymbol, number>> = {
    w: { p: 8, n: 2, b: 2, r: 2, q: 1, k: 1 },
    b: { p: 8, n: 2, b: 2, r: 2, q: 1, k: 1 }
  };

  const currentCounts: Record<Color, Record<PieceSymbol, number>> = {
    w: { p: 0, n: 0, b: 0, r: 0, q: 0, k: 0 },
    b: { p: 0, n: 0, b: 0, r: 0, q: 0, k: 0 }
  };

  const board = chess.board();
  for (const row of board) {
    for (const sq of row) {
      if (sq) {
        currentCounts[sq.color][sq.type]++;
      }
    }
  }

  const whiteCaptured: PieceSymbol[] = [];
  const blackCaptured: PieceSymbol[] = [];

  const types: PieceSymbol[] = ['q', 'r', 'b', 'n', 'p'];
  for (const t of types) {
    const bMissing = initialCounts.b[t] - currentCounts.b[t];
    for (let i = 0; i < bMissing; i++) whiteCaptured.push(t);

    const wMissing = initialCounts.w[t] - currentCounts.w[t];
    for (let i = 0; i < wMissing; i++) blackCaptured.push(t);
  }

  let wSum = 0;
  for (const p of whiteCaptured) wSum += PIECE_VALS[p];
  let bSum = 0;
  for (const p of blackCaptured) bSum += PIECE_VALS[p];

  const whiteAdvantage = Math.round((wSum - bSum) / 100);

  return { whiteCaptured, blackCaptured, whiteAdvantage };
}
